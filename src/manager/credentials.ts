/**
 * Manager credentials bootstrap.
 *
 * On first launch (no `~/.metabot/manager.env`) we generate a random admin
 * password + 32-byte session secret, bcrypt-hash the password, and persist a
 * small dotenv file (chmod 600). The plain password is loudly printed to
 * stderr inside an unmistakable banner so the owner can grep it out of the
 * PM2 log after the first start. Subsequent starts just read the file.
 */
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import * as crypto from 'node:crypto';
import bcrypt from 'bcryptjs';

export interface ManagerCredentials {
  username:           string;
  passwordHashBcrypt: string;
  sessionSecret:      string;
}

const PASSWORD_LEN = 16;
const PASSWORD_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789'; // no 0/O/1/l/I

function randomPassword(length: number): string {
  const bytes = crypto.randomBytes(length);
  let out = '';
  for (let i = 0; i < length; i += 1) {
    out += PASSWORD_ALPHABET[bytes[i] % PASSWORD_ALPHABET.length];
  }
  return out;
}

function envFilePath(): string {
  return path.join(os.homedir(), '.metabot', 'manager.env');
}

function parseEnvFile(raw: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of raw.split('\n')) {
    const m = line.match(/^([A-Z_][A-Z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m) continue;
    let val = m[2];
    if ((val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[m[1]] = val;
  }
  return out;
}

function loudBanner(plainPassword: string, filePath: string): void {
  const sep = '='.repeat(72);
  const lines = [
    sep,
    sep,
    '  metabot-manager: first-run admin credentials generated',
    `  username : admin`,
    `  password : ${plainPassword}`,
    `  saved to : ${filePath}`,
    `  Login at  : http://127.0.0.1:${process.env.MANAGER_PORT || '11000'}/manager/`,
    '  (this banner only prints once — copy the password NOW)',
    sep,
    sep,
  ];
  for (const l of lines) process.stderr.write(l + '\n');
}

/**
 * Read existing credentials or generate-and-persist new ones.
 * Returns the live credentials regardless of which path was taken.
 */
export function ensureCredentialsFile(): ManagerCredentials {
  const filePath = envFilePath();

  // Ensure ~/.metabot/ exists.
  fs.mkdirSync(path.dirname(filePath), { recursive: true });

  if (fs.existsSync(filePath)) {
    const parsed = parseEnvFile(fs.readFileSync(filePath, 'utf-8'));
    const username           = parsed.MANAGER_ADMIN_USERNAME      || 'admin';
    const passwordHashBcrypt = parsed.MANAGER_ADMIN_PASSWORD_HASH || '';
    const sessionSecret      = parsed.MANAGER_SESSION_SECRET      || '';

    if (passwordHashBcrypt && sessionSecret) {
      return { username, passwordHashBcrypt, sessionSecret };
    }
    // File is malformed / partial → fall through to regen, but back up the old
    // file so the owner can recover if their password was in there.
    try {
      fs.renameSync(filePath, filePath + '.broken.' + Date.now());
    } catch { /* ignore */ }
  }

  const plainPassword      = randomPassword(PASSWORD_LEN);
  const passwordHashBcrypt = bcrypt.hashSync(plainPassword, 10);
  const sessionSecret      = crypto.randomBytes(32).toString('hex');

  const body = [
    '# metabot-manager admin credentials — generated by ensureCredentialsFile().',
    '# Edit MANAGER_ADMIN_USERNAME or wipe this file to regenerate.',
    `MANAGER_ADMIN_USERNAME=admin`,
    `MANAGER_ADMIN_PASSWORD_HASH=${passwordHashBcrypt}`,
    `MANAGER_SESSION_SECRET=${sessionSecret}`,
    '',
  ].join('\n');
  fs.writeFileSync(filePath, body, { mode: 0o600 });

  loudBanner(plainPassword, filePath);

  return { username: 'admin', passwordHashBcrypt, sessionSecret };
}
